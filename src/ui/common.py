def tag(status: str) -> str:
    if status == "synthetic":
        return '<span class="ecsi-tag ecsi-syn">▲ SYNTHETIC</span>'
    return '<span class="ecsi-tag ecsi-real">● REAL DATA</span>'


def page_header(kicker: str, title: str, sub: str) -> None:
    st.markdown(f'<div class="ecsi-kicker">{kicker}</div>', unsafe_allow_html=True)
    st.title(title)
    st.markdown(f'<p class="ecsi-sub">{sub}</p>', unsafe_allow_html=True)
