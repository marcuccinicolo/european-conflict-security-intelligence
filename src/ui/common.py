def source_label(row: pd.Series) -> str:
    tag = "SYNTHETIC demo" if row["data_status"] == "synthetic" else "real data"
    return f"{row['name']}  ·  {tag}"


def pick_source(domain: str, key: str, label: str, container=st.sidebar) -> pd.Series:
    """Source selector that never mixes sources; defaults to real data when present."""
    reg = registry(db_version())
    reg = reg[reg["domain"] == domain].sort_values("data_status")  # real < synthetic
    options = reg["source"].tolist()
    labels = dict(zip(reg["source"], reg.apply(source_label, axis=1)))
    choice = container.selectbox(label, options, format_func=labels.get, key=key,
                                 help="Datasets are analysed one at a time; they are never pooled.")  # fmt: skip
    return reg.set_index("source").loc[choice].rename(choice)


def status_banner(row: pd.Series) -> None:
    if row["data_status"] == "synthetic":
        st.error(
            "**SYNTHETIC DEMONSTRATION DATA.** These records were generated by this project "
            "to demonstrate the pipeline. They are not real events or real expenditure figures "
            "and support no conclusion about actual conditions.",
            icon=":material/science:",
        )
    else:
        cov = row["coverage"] or {}
        span = (
            f"{cov.get('date_min', cov.get('year_min'))} to {cov.get('date_max', cov.get('year_max'))}"
        )
        st.success(
            f"**Real public data:** {row['name']} ({row['publisher']}). Coverage {span}. "
            f"Licence: {row['licence']}. Retrieved {str(row['retrieved_at_utc'])[:10]}.",
            icon=":material/verified:",
        )


def md(text) -> str:
    """Escape '$' so Streamlit markdown does not render 'US$ ... $' as LaTeX."""
    return str(text).replace("$", "\\$")


def fmt_int(x) -> str:
    return "—" if x is None or pd.isna(x) else f"{int(round(x)):,}"


def fmt_pct(x, digits: int = 0) -> str:
    return "—" if x is None or pd.isna(x) else f"{x * 100:.{digits}f}%"


