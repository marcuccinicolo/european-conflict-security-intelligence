def _first(directory: Path, patterns: tuple[str, ...]) -> Path | None:
    for pat in patterns:
        found = sorted(Path(directory).glob(pat))
        if found:
            return found[-1]  # latest version by name
    return None


def _registry_row(key: str, domain: str, data_status: str, report, files: list[Path],
                  prov: list[dict] | None = None) -> dict:  # fmt: skip
    spec = SOURCES[key]
    prov = prov if prov is not None else [fetch_mod.read_provenance(f) for f in files]
    if data_status == "synthetic":
        prov = [{**p, "method": "generated by scripts/generate_synthetic_data.py (bundled)"} for p in prov]
    return {
        "source": key,
        "domain": domain,
        "name": spec.name,
        "publisher": spec.publisher,
        "data_status": data_status,
        "licence": spec.licence,
        "licence_url": spec.licence_url,
        "url": spec.url,
        "citation": spec.citation,
        "redistribution": spec.redistribution,
        "exportable": key in EXPORTABLE_SOURCES,
        "input_file": report.input_file,
        "retrieved_at_utc": ", ".join(p["retrieved_at_utc"] for p in prov),
        "retrieval_method": ", ".join(p["method"] for p in prov),
        "sha256": ", ".join(p["sha256"][:16] for p in prov),
        "rows_in": report.rows_in,
        "rows_out": report.rows_out,
        "coverage": report.coverage,
        "transformations": report.transformations,
        "notes": spec.notes,
        "processed_at_utc": report.generated_at,
    }


def _checks(report) -> list[dict]:
    d = report.to_dict()
    return [
        {
            "source": report.source,
            "check_name": c["name"],
            "status": c["status"],
            "affected_rows": c["affected_rows"],
            "total_rows": c["total_rows"],
            "share": c["share"],
            "detail": c["detail"],
            "action": c["action"],
        }
        for c in d["checks"]
    ]


def export_public_events(df, report, raw_files: list[Path], key: str, parquet: Path, meta_path: Path) -> None:
    """Write a validated European subset (CC BY 4.0 permits redistribution).

    The sidecar keeps the ORIGINAL files' provenance and the full quality report,
    so a deployment built from the subset shows the same lineage and checks.
    """
    parquet.parent.mkdir(parents=True, exist_ok=True)
    df.to_parquet(parquet, index=False)
    meta = {
        "description": f"Validated European subset of {SOURCES[key].name}, produced by `python -m src.pipeline build`.",
        "licence": "CC BY 4.0 - " + SOURCES[key].citation,
        "source_provenance": [fetch_mod.read_provenance(f) for f in raw_files],
        "quality_report": report.to_dict(),
    }
    meta_path.write_text(json.dumps(meta, indent=2, default=str))


def export_public_ucdp(df, report, raw_file: Path) -> None:
    export_public_events(df, report, [raw_file], "ucdp_ged", UCDP_PUBLIC_PARQUET, UCDP_PUBLIC_META)


def load_public_events(parquet: Path, meta_path: Path):
    meta = json.loads(meta_path.read_text())
    df = conform(pd.read_parquet(parquet), EVENT_COLUMNS)
    report = QualityReport.from_dict(meta["quality_report"])
    report.transformations.append(
        f"Loaded from the committed validated subset {parquet.name} (raw files not present in this environment)."
    )
    provs = meta["source_provenance"]
    provs = provs if isinstance(provs, list) else [provs]
    out = []
    for prov in provs:
        prov = dict(prov)
        prov["method"] = f"{prov['method']} (via committed subset {parquet.name})"
        out.append(prov)
    return df, report, out


def load_public_ucdp():
    return load_public_events(UCDP_PUBLIC_PARQUET, UCDP_PUBLIC_META)


def candidate_year() -> int:
    """The year after the latest annual GED: what the Candidate releases cover."""
    if UCDP_PUBLIC_META.exists():
        cov = json.loads(UCDP_PUBLIC_META.read_text())["quality_report"]["coverage"]
        return int(str(cov["date_max"])[:4]) + 1
    return datetime.now(timezone.utc).year


def build_or_load_candidate():
    spec = SOURCES["ucdp_candidate"]
    raw = sorted(spec.raw_dir.glob("GEDEvent_v*.csv"), key=fetch_mod.release_sort_key)
    if raw:
        df, rep = load_candidate(raw, candidate_year())
        export_public_events(df, rep, raw, "ucdp_candidate", CANDIDATE_PUBLIC_PARQUET, CANDIDATE_PUBLIC_META)
        return df, rep, raw, None
    if CANDIDATE_PUBLIC_PARQUET.exists():
        df, rep, prov = load_public_events(CANDIDATE_PUBLIC_PARQUET, CANDIDATE_PUBLIC_META)
        return df, rep, [], prov
    print("  ucdp_candidate    not found - run `python -m src.pipeline fetch`")
    return None, None, None, None


def build_or_load_exposure(ucdp_df):
    """Distances from raw boundary files when present; otherwise the committed CSV."""
    from src.config import BOUNDARIES_ZIP

    if exposure_mod.PLACES_ZIP.exists() and BOUNDARIES_ZIP.exists() and ucdp_df is not None:
        ex = exposure_mod.build_exposure(ucdp_df)
        EXPOSURE_PUBLIC_CSV.parent.mkdir(parents=True, exist_ok=True)
        ex.to_csv(EXPOSURE_PUBLIC_CSV, index=False)
        files, how = [exposure_mod.PLACES_ZIP, BOUNDARIES_ZIP], "computed from Natural Earth + UCDP"
    elif EXPOSURE_PUBLIC_CSV.exists():
        ex = pd.read_csv(EXPOSURE_PUBLIC_CSV)
        ex["nato_accession_year"] = ex["nato_accession_year"].astype("Int64")
        files, how = [EXPOSURE_PUBLIC_CSV], f"loaded from committed {EXPOSURE_PUBLIC_CSV.name}"
    else:
        print("  exposure          not available - run `python -m src.pipeline fetch`")
        return None, None, None
    rep = QualityReport(source="exposure", input_file=", ".join(f.name for f in files))
    rep.rows_in = rep.rows_out = len(ex)
    rep.add("capitals_found", "pass" if len(ex) >= 40 else "warn", len(ex), len(ex),
            f"{len(ex)} European capitals matched (Natural Earth 'Admin-0 capital').")  # fmt: skip
    neg = int((ex["dist_russia_km"] < 0).sum())
    rep.add("distances_non_negative", "fail" if neg else "pass", neg, len(ex), "Distances must be >= 0.")
    miss = int(ex["dist_front_km"].isna().sum())
    rep.add("missing_dist_front", "warn" if miss else "pass", miss, len(ex),
            "Distance to nearest UCDP Russia-Ukraine event (2022-2025) missing.")  # fmt: skip
    rep.transformations += [how, "Russia polygon with the Crimea part removed before measuring distance.",
                            "NATO accession years from data/reference/nato_accession.csv (nato.int)."]  # fmt: skip
    rep.coverage = {"n_entities": int(len(ex))}
    return ex, rep, files


def build_or_load_wdi():
    if worldbank.RAW_JSON.exists():
        df, rep = worldbank.load_wdi(worldbank.RAW_JSON)
        WDI_PUBLIC_CSV.parent.mkdir(parents=True, exist_ok=True)
        df.to_csv(WDI_PUBLIC_CSV, index=False)
        return df, rep, [worldbank.RAW_JSON]
    if WDI_PUBLIC_CSV.exists():
        df = pd.read_csv(WDI_PUBLIC_CSV)
        rep = QualityReport(source="world_bank_wdi", input_file=WDI_PUBLIC_CSV.name)
        rep.rows_in = rep.rows_out = len(df)
        rep.add("loaded_committed_copy", "info", 0, len(df), "Raw API file absent; committed CSV used.")
        rep.coverage = {"year_min": int(df["year"].min()), "year_max": int(df["year"].max()),
                        "n_entities": int(df["iso3"].nunique())}  # fmt: skip
        return df, rep, [WDI_PUBLIC_CSV]
    print("  world_bank_wdi    not available - run `python -m src.pipeline fetch`")
    return None, None, None


def cmd_fetch(args) -> None:
    print("Fetching official public datasets")
    fetch_mod.fetch_ucdp(force=args.force)
    fetch_mod.fetch_sipri(force=args.force)
    fetch_mod.fetch_boundaries(force=args.force)
    fetch_mod.download(exposure_mod.PLACES_URL, exposure_mod.PLACES_ZIP, args.force)
    year = candidate_year()
    print(f"  UCDP Candidate releases for {year}")
    for f in fetch_mod.fetch_candidate(year, force=args.force):
        print(f"    {f.name}")
    if args.force or not worldbank.RAW_JSON.exists():
        print("  downloading World Bank WDI (API)")
        worldbank.fetch_wdi()
    if args.acled:
        print("Fetching ACLED via API")
        print(f"  wrote {fetch_mod.fetch_acled(start=args.acled_start)}")


def cmd_build(args=None) -> Path:
    events, milex, registry, checks, summary = [], [], [], [], {}

    def record(key, domain, status, df, report, files, prov=None):
        path = report.write(QUALITY_DIR)
        registry.append(_registry_row(key, domain, status, report, files, prov))
        checks.extend(_checks(report))
        summary[key] = {"rows_out": report.rows_out, **report.to_dict()["summary"],
                        "report": str(path.relative_to(QUALITY_DIR.parents[1]))}  # fmt: skip
        print(f"  {key:<17} {report.rows_out:>7} rows  {report.to_dict()['summary']}")

    print("Building analytical database")
    from src.data.boundaries import export_public_boundaries

    export_public_boundaries()
    df, rep = load_acled_csv(SYNTHETIC_EVENTS_CSV, source="synthetic_events")
    events.append(df)
    record("synthetic_events", "conflict", "synthetic", df, rep, [SYNTHETIC_EVENTS_CSV])

    ucdp_df = None
    ucdp = _first(SOURCES["ucdp_ged"].raw_dir, ("ged*-csv.zip", "GEDEvent*.csv", "*.zip"))
    if ucdp:
        df, rep = load_ucdp(ucdp)
        ucdp_df = df
        events.append(df)
        record("ucdp_ged", "conflict", "real", df, rep, [ucdp])
        export_public_ucdp(df, rep, ucdp)
    elif UCDP_PUBLIC_PARQUET.exists():
        df, rep, prov = load_public_ucdp()
        ucdp_df = df
        events.append(df)
        record("ucdp_ged", "conflict", "real", df, rep, [], prov)
    else:
        print("  ucdp_ged          not found - run `python -m src.pipeline fetch`")

    cdf, crep, cfiles, cprov = build_or_load_candidate()
    if cdf is not None:
        events.append(cdf)
        record("ucdp_candidate", "conflict", "real", cdf, crep, cfiles, cprov)

    acled_dir = SOURCES["acled"].raw_dir
    if acled_files(acled_dir):
        df, rep = load_acled_dir(acled_dir)
        events.append(df)
        record("acled", "conflict", "real", df, rep, acled_files(acled_dir))
    else:
        print("  acled             not found - optional, see docs/DATA_ACQUISITION.md")

    df, rep = load_milex_csv(SYNTHETIC_MILEX_CSV)
    milex.append(df)
    record("synthetic_milex", "defence", "synthetic", df, rep, [SYNTHETIC_MILEX_CSV])

    sipri = _first(SOURCES["sipri_milex"].raw_dir, ("SIPRI-Milex-data-*.xlsx",))
    if sipri:
        df, rep = load_sipri(sipri)
        milex.append(df)
        record("sipri_milex", "defence", "real", df, rep, [sipri])
    else:
        print("  sipri_milex       not found - run `python -m src.pipeline fetch`")

    extra = {}
    ex, ex_rep, ex_files = build_or_load_exposure(ucdp_df)
    if ex is not None:
        extra["exposure"] = ex
        record("exposure", "research", "real", ex, ex_rep, ex_files)
    wdi, wdi_rep, wdi_files = build_or_load_wdi()
    if wdi is not None:
        extra["macro"] = wdi
        record("world_bank_wdi", "research", "real", wdi, wdi_rep, wdi_files)

    path = build_database(events, milex, registry, checks, extra_tables=extra)
    index = {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "database": path.name,
        "sources": summary,
    }
    (QUALITY_DIR / "index.json").write_text(json.dumps(index, indent=2))
    print(f"Database written to {path}")
    return path


def cmd_refresh(args=None) -> Path:
    """Monthly refresh used by CI: new Candidate releases -> build -> brief -> summary.

    Writes reports/refresh_summary.md, used as the pull-request description.
    """
    before = _candidate_state()
    year = candidate_year()
    fetch_mod.fetch_sipri()  # needed for the brief; never committed
    files = fetch_mod.fetch_candidate(year)
    cmd_build()
    cmd_report()
    after = _candidate_state()
    lines = [f"## Monthly data refresh ({datetime.now(timezone.utc).date()})", "",
             f"UCDP Candidate releases for {year}: " + ", ".join(f"`{f.name}`" for f in files), "",
             "| | Before | After |", "|---|---|---|"]  # fmt: skip
    for k in ("events", "date_max", "share_clear"):
        lines.append(f"| {k} | {before.get(k, '—')} | {after.get(k, '—')} |")
    lines += ["", "Candidate data are **provisional**: not comparable with UCDP GED and revised in the next "
              "annual release. Check `reports/data_quality/ucdp_candidate.json` before merging."]  # fmt: skip
    path = QUALITY_DIR.parents[0] / "refresh_summary.md"
    path.write_text("\n".join(lines) + "\n")
    print(path.read_text())
    return path


def _candidate_state() -> dict:
    if not CANDIDATE_PUBLIC_META.exists():
        return {}
    q = json.loads(CANDIDATE_PUBLIC_META.read_text())["quality_report"]
    clear = next((c for c in q["checks"] if c["name"] == "code_status[Clear]"), None)
    return {"events": q["coverage"].get("events"), "date_max": q["coverage"].get("date_max"),
            "share_clear": f"{clear['affected_rows'] / clear['total_rows']:.1%}" if clear else "—"}  # fmt: skip


def cmd_report(args=None) -> None:
    from src.report import build_report

    for p in build_report():
        print(f"  wrote {p}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m src.pipeline", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)  # fmt: skip
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("fetch", "all"):
        p = sub.add_parser(name)
        p.add_argument("--force", action="store_true", help="re-download existing files")
        p.add_argument("--acled", action="store_true", help="also fetch ACLED (credentials)")
        p.add_argument("--acled-start", default="2018-01-01")
    sub.add_parser("build")
    sub.add_parser("report")
    sub.add_parser("refresh", help="monthly CI refresh: Candidate data, build, report, summary")
    args = ap.parse_args(argv)
    if args.cmd == "fetch":
        cmd_fetch(args)
    elif args.cmd == "build":
        cmd_build(args)
    elif args.cmd == "report":
        cmd_report(args)
    elif args.cmd == "refresh":
        cmd_refresh(args)
    elif args.cmd == "all":
        cmd_fetch(args)
        cmd_build(args)
        cmd_report(args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
